def normalize_prop_tag(label: str) -> str:
    """Normalize a human prop label into a project-safe tag.

    Examples:
        "Coffee Cup"       -> "coffee-cup"
        "Espresso Machine" -> "espresso-machine"
        "cup2"             -> "cup2"
        "Barista Bar"      -> "barista-bar"
    """
    import re

    s = label.strip().lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    s = re.sub(r"-+", "-", s)
    s = s.strip("-")
    return s or "prop"
