def deep_fill(locale: str) -> dict[str, dict[str, str]]:
    """Fill all namespaces for a locale; fall back to EN then overlay TR."""
    out: dict[str, dict[str, str]] = {}
    for ns, keys in EN.items():
        out[ns] = dict(keys)
        if locale in TR and ns in TR[locale]:
            out[ns].update(TR[locale][ns])
    return out


