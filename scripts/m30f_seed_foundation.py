def write_locales() -> None:
    WEB_I18N.mkdir(parents=True, exist_ok=True)
    (WEB_I18N / "locales").mkdir(exist_ok=True)
    for code, *_ in LOCALES:
        data = deep_fill(code)
        if code in COMPACT:
            for ns, keys in COMPACT[code].items():
                data.setdefault(ns, {}).update(keys)
        loc_dir = WEB_I18N / "locales" / code
        loc_dir.mkdir(parents=True, exist_ok=True)
        for ns in NAMESPACES:
            payload = data.get(ns) or EN.get(ns, {})
            (loc_dir / f"{ns}.json").write_text(
                json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
    meta = {
        "locales": [
            {
                "locale": c,
                "displayName": d,
                "nativeName": n,
                "direction": direction,
                "fallback": "en",
                "enabled": True,
                "status": status,
                "reviewLevel": review,
                "dateLocale": date_l,
                "numberLocale": num_l,
                "notes": "Portuguese uses Brazilian Portuguese (pt-BR) conventions." if c == "pt" else "",
            }
            for c, d, n, direction, date_l, num_l, status, review in LOCALES
        ],
        "namespaces": NAMESPACES,
        "betaCriticalNamespaces": [
            "common",
            "navigation",
            "codirector",
            "production-bible",
            "director",
            "editor",
            "jobs",
            "errors",
            "settings",
            "accessibility",
            "approval",
            "export",
        ],
    }
    (WEB_I18N / "locale-meta.json").write_text(
        json.dumps(meta, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Wrote locales under {WEB_I18N / 'locales'}")


def main() -> None:
    write_locales()
    DOCS.mkdir(parents=True, exist_ok=True)
    print("OK")


if __name__ == "__main__":
    main()
